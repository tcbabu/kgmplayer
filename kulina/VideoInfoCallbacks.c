void * VideoInfoInterface(void *args,void *rets) {
  /*********************************** 
   ***********************************/ 
  DIAINTR *it= (DIAINTR *)malloc(sizeof(DIAINTR));
  it->GrpId=0;
  // filled by MakeGroup  it->xsh=0;
  it->ysh=0;
  it->RunDia = RunVideoInfo;
  it->MakeGroup = MakeVideoInfoGroup;
  it->Title = GetPointer((char *)"VideoInfo");
  it->Help = GetPointer( (char *)"No help yet, request");
  it->Action = VideoInfoAction;
  it->Settings = VideoInfoSetup;
  it->Cleanup  = VideoInfoCleanDia;
  if(args != NULL) Args=args;
  if(rets != NULL) Rets=rets;
  it->args = Args;
  it->rets = Rets;
  it->SwitchOn = VideoInfoOn;
  it->SwitchOff = VideoInfoOff;
  it->Dtmp = NULL; // fiiled by MakeGroup 
  It = it;
  return it;
}
 
 
